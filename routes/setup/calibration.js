router.post('/api/parts/:id/markers', express.json(), async (req, res) => {
    try {
        const { name, kind = 'absolute', value, unit, speed, durationMs, locked } = req.body || {};
        if (!name || !name.trim()) return res.status(400).json({ success: false, error: 'name required' });
        const ctx = await resolveCharacter(req);
        const characterId = ctx ? ctx.id : null;
        let parts = await loadCharacterParts(characterId);
        let idx = parts.findIndex(p => String(p.id) === String(req.params.id));
        if (idx === -1) {
            // If part not present in per-character file yet, seed from global parts.json
            try {
                const globalParts = await loadParts();
                const source = globalParts.find(p => String(p.id) === String(req.params.id));
                if (source) {
                    parts = parts.concat([{ ...source }]);
                    idx = parts.length - 1;
                }
            } catch (_) { /* ignore */ }
        }
        if (idx === -1) return res.status(404).json({ success: false, error: 'Part not found' });
        const markers = Array.isArray(parts[idx].markers) ? parts[idx].markers : [];
        const i2 = markers.findIndex(m => m.name === name);
        const next = { name: name.trim(), kind, locked: !!locked };
        if (kind === 'absolute') {
            // Markers are a first-class calibration source — the jaw and
            // head-tracking guardrails read Min/Max straight from here. This
            // endpoint used to store anything at all: a non-numeric value made
            // NaN guardrails (both clamp comparisons false → NO clamp on an
            // unmeasured servo), and a Min==Max pair pinned the part at one
            // angle. Validate like the profile writers do.
            const num = Number(value);
            if (!Number.isFinite(num)) {
                return res.status(400).json({ success: false, error: 'Marker value must be a finite number' });
            }
            // Validate against the part's REAL rotation range — 180 unless it
            // declares a multi-turn span (the knight's 900° head). A hard 180
            // here made Min/Max markers unrecordable for exactly the part whose
            // guardrails need them most.
            const markerSpanMax = Number(parts[idx].config && parts[idx].config.rotationRangeDeg) > 0
                ? Number(parts[idx].config.rotationRangeDeg) : 180;
            if (parts[idx].type === 'servo' && (num < 0 || num > markerSpanMax)) {
                return res.status(400).json({ success: false, error: `Servo marker must be within 0-${markerSpanMax}°` });
            }
            if (parts[idx].type === 'servo' && (name.trim() === 'Min' || name.trim() === 'Max')) {
                const sibling = markers.find(m => m.name === (name.trim() === 'Min' ? 'Max' : 'Min'));
                const sibVal = sibling ? Number(sibling.value) : null;
                if (sibVal != null && Number.isFinite(sibVal)) {
                    const minA = name.trim() === 'Min' ? num : sibVal;
                    const maxA = name.trim() === 'Min' ? sibVal : num;
                    if ((maxA - minA) < 1) {
                        return res.status(409).json({
                            success: false,
                            error: `Refusing ${name.trim()} = ${num}°: the Min/Max window would collapse to nothing ` +
                                   `and lock the servo at one angle. Move the servo to a genuinely different position first.`
                        });
                    }
                }
            }
            next.value = num;
            if (unit) next.unit = unit;
        }
        if (kind === 'preset') { next.speed = speed; next.durationMs = durationMs; }
        if (i2 === -1) markers.push(next); else markers[i2] = next;
        parts[idx].markers = markers;
        await saveCharacterParts(characterId, parts);
        res.json({ success: true, markers });
    } catch (e) {
        console.error('save marker failed', e);
        res.status(500).json({ success: false, error: 'Failed to save marker' });
    }
});

