/**
 * Calibration services, backed by the REAL persistence layer.
 *
 * These were stubs: every `getCalibrationStatus` returned a hard-coded
 * `{pulseCalibrated:true, positionsCalibrated:true}` and every save reported
 * `success:true` while writing nothing. That is the most dangerous shape a bug can
 * take on this page — an uncalibrated 150 kg servo reported as calibrated is how
 * hardware gets destroyed, and the fabricated success meant an operator who did the
 * work correctly still had nothing saved.
 *
 * Everything below reads and writes `data/calibration_profiles.json` through
 * `server/calibration/store.js` — the same store the `/api/calibration` API and the
 * jaw/head/animation runtime use — so this page can no longer disagree with them.
 * Where a fact is genuinely unknown, these report it as unknown rather than true.
 *
 * The store is read with `getRaw()` here on purpose: this code's job is to REPORT
 * on the calibration (including whether it is only a placeholder) and to
 * read-modify-write it. Anything that MOVES hardware must use `store.get()`, which
 * withholds a placeholder's guessed span.
 */
const calibrationStore = getCalibrationStore();

/**
 * The store distinguishes `undefined` ("no character given — fall back to the
 * node's selected character") from `null` ("explicitly unscoped"), and an
 * unscoped write lands on a legacy bare-partId key that every character shares.
 * A handler that simply couldn't resolve a character means the former, so
 * normalize before anything reaches the store.
 */
function storeScope(characterId) {
    return characterId == null ? undefined : characterId;
}

async function readProfileRaw(partId, characterId) {
    try {
        return await calibrationStore.getRaw(partId, storeScope(characterId));
    } catch (err) {
        console.warn(`Calibration profile read failed for part ${partId}:`, err && err.message);
        return null;
    }
}

function blankProfile(partId, kind) {
    const numericId = /^\d+$/.test(String(partId)) ? parseInt(partId, 10) : partId;
    return {
        partId: numericId,
        capability: kind === 'openloop-linear'
            ? { kind: 'openloop-linear' }
            : { kind, usMin: 500, usMax: 2500 },
        bounds: kind === 'absolute-servo' ? { minAngle: 0, maxAngle: 180 } : null,
        presets: [],
        motion: {},
        version: 1,
        // A profile created as a side effect of saving a pulse or a preset is still
        // NOT a calibration. The flag is only cleared where a human has physically
        // established an end stop.
        autoGenerated: true
    };
}

async function mutateProfile(partId, characterId, kind, mutate) {
    const existing = await readProfileRaw(partId, characterId);
    const profile = existing || blankProfile(partId, kind);
    mutate(profile);
    await calibrationStore.upsert(profile, storeScope(characterId));
    return profile;
}

/** Shared shape so every status answer names its source and its confidence. */
function baseStatus(profile) {
    if (!profile) {
        return {
            exists: false,
            placeholder: false,
            source: 'none',
            reason: 'No calibration profile exists for this part — it has never been calibrated.'
        };
    }
    const placeholder = isPlaceholderProfile(profile);
    return {
        exists: true,
        placeholder,
        source: 'calibration_profiles.json',
        lastCalibratedAt: profile.lastCalibratedAt || null,
        reason: placeholder
            ? 'A profile exists but it is the auto-generated full-span placeholder, not a measurement.'
            : undefined
    };
}

function presetsOf(profile) {
    return (profile && Array.isArray(profile.presets)) ? profile.presets : [];
}

/** Measured bounds only — a placeholder's span is not a measurement. */
function measuredBounds(profile) {
    if (!profile || isPlaceholderProfile(profile)) return null;
    return profile.bounds || null;
}

const standardServoCalibration = {
    async getCalibrationStatus(partId, characterId) {
        const profile = await readProfileRaw(partId, characterId);
        const base = baseStatus(profile);
        const pulses = (profile && profile.pulses) || {};
        const pulseCalibrated = typeof pulses.minUs === 'number' && typeof pulses.maxUs === 'number';
        const bounds = measuredBounds(profile);
        const boundsCalibrated = !!(bounds
            && typeof bounds.minAngle === 'number' && typeof bounds.maxAngle === 'number');
        const presets = presetsOf(profile);
        const positionsCalibrated = boundsCalibrated || presets.length > 0;
        return {
            ...base,
            pulseCalibrated,
            positionsCalibrated,
            boundsCalibrated,
            calibrated: pulseCalibrated || positionsCalibrated,
            minAngle: boundsCalibrated ? bounds.minAngle : null,
            maxAngle: boundsCalibrated ? bounds.maxAngle : null,
            pulses,
            positionCount: presets.length
        };
    },

    /** Starting points offered to the operator — a suggestion, never a status. */
    getSuggestedPositions(partName) {
        return [{ name: 'min', value: 0 }, { name: 'mid', value: 90 }, { name: 'max', value: 180 }];
    },

    async savePulse(partId, partName, pulseType, us, channel, characterId) {
        const field = { min: 'minUs', center: 'centerUs', max: 'maxUs' }[String(pulseType)];
        if (!field) throw new Error(`Unknown pulseType "${pulseType}" (expected min, center or max)`);
        const profile = await mutateProfile(partId, characterId, 'absolute-servo', (p) => {
            p.pulses = Object.assign({}, p.pulses, { [field]: us });
            p.capability = Object.assign({ kind: 'absolute-servo' }, p.capability || {});
            if (field === 'minUs') p.capability.usMin = us;
            if (field === 'maxUs') p.capability.usMax = us;
            if (channel != null) p.capability.channel = channel;
            // autoGenerated is deliberately NOT cleared: a pulse width is not an angle
            // bound, and clearing it here would promote the placeholder 0-180 span to a
            // measurement for every consumer that reads this profile.
        });
        return { success: true, persisted: true, partId: String(partId), pulseType, us, pulses: profile.pulses };
    },

    async savePosition(partId, partName, posName, description, channel, data, characterId) {
        const name = String(posName || '').trim();
        if (!name) throw new Error('Position name is required');
        // The part's real rotation range, from its own config: a profile born
        // here via blankProfile() carries no maxAngleDeg, and normalizing a
        // 450° position over 180 wrote p=1.0 — replayed by the scene executor
        // as FULL travel instead of the saved angle.
        let declaredRange = 0;
        try {
            const parts = await loadCharacterParts(characterId);
            const part = parts.find(x => String(x.id) === String(partId));
            declaredRange = Number(part && part.config && part.config.rotationRangeDeg) || 0;
        } catch (_) { /* fall through — profile capability may still carry it */ }
        const profile = await mutateProfile(partId, characterId, 'absolute-servo', (p) => {
            const presets = presetsOf(p).slice();
            const entry = { name, description: description || '' };
            // Keep the profile's declared range in step with the part config —
            // a blankProfile() creation has no part context to stamp it from.
            if (declaredRange > 0 && p.capability && p.capability.maxAngleDeg == null && declaredRange !== 180) {
                p.capability.maxAngleDeg = declaredRange;
            }
            const angle = data && data.angle != null ? Number(data.angle) : null;
            if (angle != null && Number.isFinite(angle)) {
                entry.angle = angle;
                // Presets are read back by the scene executor, which accepts either an
                // angle or a normalized p. Write both so neither path guesses. p is
                // normalized over the part's REAL span (multi-turn parts declare
                // capability.maxAngleDeg / config.rotationRangeDeg), never a hardcoded 180.
                const fullSpanDeg = (p.capability && Number(p.capability.maxAngleDeg) > 0)
                    ? Number(p.capability.maxAngleDeg)
                    : (declaredRange > 0 ? declaredRange : 180);
                entry.p = Math.max(0, Math.min(1, angle / fullSpanDeg));
            }
            if (data && data.speed != null) entry.speed = Number(data.speed);
            if (data && data.duration != null) entry.duration = Number(data.duration);
            const i = presets.findIndex(x => x && x.name === name);
            if (i === -1) presets.push(entry); else presets[i] = Object.assign({}, presets[i], entry);
            p.presets = presets;
        });
        return { success: true, persisted: true, partId: String(partId), posName: name, positions: profile.presets };
    },

    async listPositions(partId, characterId) {
        return presetsOf(await readProfileRaw(partId, characterId));
    },

    async deletePosition(partId, posName, characterId) {
        const profile = await readProfileRaw(partId, characterId);
        const presets = presetsOf(profile);
        if (!presets.some(x => x && x.name === String(posName))) return false;
        await mutateProfile(partId, characterId, 'absolute-servo', (p) => {
            p.presets = presetsOf(p).filter(x => !(x && x.name === String(posName)));
        });
        return true;
    },

    async updatePosition(partId, posName, data, characterId) {
        const profile = await readProfileRaw(partId, characterId);
        const presets = presetsOf(profile);
        if (!presets.some(x => x && x.name === String(posName))) return false;
        await mutateProfile(partId, characterId, 'absolute-servo', (p) => {
            p.presets = presetsOf(p).map(x =>
                (x && x.name === String(posName)) ? Object.assign({}, x, data || {}, { name: x.name }) : x);
        });
        return true;
    }
};

const continuousServoCalibration = {
    async getCalibrationStatus(partId, characterId) {
        const profile = await readProfileRaw(partId, characterId);
        const base = baseStatus(profile);
        const pulses = (profile && profile.pulses) || {};
        // A continuous servo is calibrated by its stop/neutral pulse, not by angles.
        const pulseCalibrated = typeof pulses.centerUs === 'number' || typeof pulses.stopUs === 'number';
        const presets = presetsOf(profile);
        return {
            ...base,
            pulseCalibrated,
            positionsCalibrated: presets.length > 0,
            calibrated: pulseCalibrated || presets.length > 0,
            pulses,
            positionCount: presets.length
        };
    },

    async resetCalibration(partId, characterId) {
        return await calibrationStore.delete(partId, storeScope(characterId));
    }
};

const linearActuatorCalibration = {
    async getCalibrationStatus(partId, characterId) {
        const profile = await readProfileRaw(partId, characterId);
        const base = baseStatus(profile);
        const bounds = measuredBounds(profile);
        const minCalibrated = !!(bounds && typeof bounds.minP === 'number');
        const maxCalibrated = !!(bounds && typeof bounds.maxP === 'number');
        return {
            ...base,
            minCalibrated,
            maxCalibrated,
            fullyCalibrated: minCalibrated && maxCalibrated,
            calibrated: minCalibrated || maxCalibrated,
            bounds: bounds || null
        };
    },

    // Signature matches the call site: (partId, partName, 'min'|'max', description).
    async savePosition(partId, partName, position, description, characterId) {
        const which = String(position || '').toLowerCase();
        if (which !== 'min' && which !== 'max') throw new Error('position must be "min" or "max"');
        const endP = which === 'min' ? 0 : 1;
        const profile = await mutateProfile(partId, characterId, 'openloop-linear', (p) => {
            p.capability = Object.assign({ kind: 'openloop-linear' }, p.capability || {});
            p.bounds = Object.assign({}, p.bounds || {}, which === 'min' ? { minP: 0 } : { maxP: 1 });
            // The operator has physically parked the actuator at this end stop, so
            // this bound IS a measurement — same rule the /api/calibration set-min and
            // set-max handlers follow.
            p.autoGenerated = false;
        });
        // Keep the open-loop position tracker consistent with the end stop just set,
        // exactly as /api/calibration/:partId/set-min does. Without this the actuator
        // "knows" it is somewhere it is not.
        try {
            actuatorPositionStore.markStopped(partId, endP, storeScope(characterId));
        } catch (err) {
            console.warn(`Could not persist actuator position for part ${partId}:`, err && err.message);
        }
        return { success: true, persisted: true, partId: String(partId), position: which, bounds: profile.bounds };
    },

    async resetCalibration(partId, characterId) {
        return await calibrationStore.delete(partId, storeScope(characterId));
    }
};

