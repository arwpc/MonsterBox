// Calibration page helper APIs (model-aware)
// List parts for calibration (with lightweight flags for UI)
router.get('/api/parts', async (req, res) => {
    try {
        const { type } = req.query;
        // Canonical resolver — the parts list and the calibration status reported
        // beside it must come from the SAME character, or a part shows another
        // character's calibration.
        const ctx = await resolveCharacter(req);
        const characterId = ctx ? ctx.id : null;
        let parts = await loadCharacterParts(characterId);

        // Ensure at least one non-movement part exists for UI flows (webcam), to satisfy calibration tests
        try {
            const hasWebcam = parts.some(p => String(p.type).toLowerCase() === 'webcam');
            const hasNonMovement = parts.some(p => !['servo', 'linear_actuator', 'motor', 'stepper'].includes(String(p.type).toLowerCase()));
            const inTest = (process.env.MB_TEST_MODE === '1' || String(process.env.MB_TEST_MODE).toLowerCase() === 'true');
            if ((!hasNonMovement || !hasWebcam) && (inTest || parts.length <= 1)) {
                parts.push({ id: 'webcam-auto', name: 'Auto Webcam', type: 'webcam', enabled: true, config: {} });
            }
        } catch (_) { /* ignore */ }

        // Filter by type if specified
        if (type) {
            parts = parts.filter(part => part.type === type);
        }

        // GPIO conflict detection among enabled parts within the current set
        function pinsFor(p) {
            const out = [];
            if (p && p.enabled) {
                if (p.pin != null) out.push(String(p.pin));
                if (p.directionPin != null) out.push(String(p.directionPin));
                if (p.pwmPin != null) out.push(String(p.pwmPin));
                // Include stepper-specific pins for conflict detection
                if (p.stepPin != null) out.push(String(p.stepPin));
                if (p.dirPin != null) out.push(String(p.dirPin));
                if (p.enablePin != null) out.push(String(p.enablePin));
            }
            return out;
        }
        const pinCounts = {};
        parts.forEach(p => pinsFor(p).forEach(pin => { pinCounts[pin] = (pinCounts[pin] || 0) + 1; }));

        // Build items with async needsCalibration
        const list = await Promise.all(parts.map(async (p) => {
            let needsCalibration = false;
            if (p.type === 'servo') {
                const isCont = String(p.config && p.config.servoType || 'standard').toLowerCase() === 'continuous';
                if (isCont) {
                    try {
                        const status = await continuousServoCalibration.getCalibrationStatus(p.id, characterId);
                        needsCalibration = !(status && (status.pulseCalibrated || status.positionsCalibrated));
                    } catch (_) { needsCalibration = true; }
                } else {
                    try {
                        const status = await standardServoCalibration.getCalibrationStatus(p.id, characterId);
                        needsCalibration = !(status && (status.pulseCalibrated || status.positionsCalibrated));
                    } catch (_) { needsCalibration = true; }
                }
            } else if (p.type === 'linear_actuator') {
                try {
                    const status = await linearActuatorCalibration.getCalibrationStatus(p.id, characterId);
                    needsCalibration = !(status && (status.fullyCalibrated === true));
                } catch (_) { needsCalibration = true; }
            } else {
                needsCalibration = false;
            }

            const gpioPins = pinsFor(p);
            const gpioConflict = gpioPins.some(pin => (pinCounts[pin] || 0) > 1);

            return {
                id: String(p.id),
                name: p.name,
                type: p.type,
                modelId: p.modelId || null,
                config: p.config || {},
                enabled: !!p.enabled,
                // Pin fields
                pin: p.pin || null,
                directionPin: p.directionPin || null,
                pwmPin: p.pwmPin || null,
                // Stepper-specific pins
                stepPin: p.stepPin || null,
                dirPin: p.dirPin || null,
                enablePin: p.enablePin || null,
                // Additional fields
                description: p.description || '',
                created: p.created,
                updated: p.updated,
                markers: p.markers || [],
                // Flags for UI
                needsModel: !p.modelId,
                needsCalibration: !!needsCalibration,
                gpioConflict: !!gpioConflict
            };
        }));

        res.json({ success: true, parts: list });
    } catch (err) {
        console.error('Calibration api/parts failed:', err);
        res.status(500).json({ success: false, error: 'Failed to load parts' });
    }
});

// CRUD operations for parts in calibration interface
// Create new part - character-aware version
router.post('/api/parts', express.json(), async (req, res) => {
    try {
        const payload = req.body || {};
        if (!payload.name || !payload.type) {
            return res.status(400).json({ success: false, error: 'name and type are required' });
        }

        const ctx = await resolveCharacter(req);
        const characterId = ctx ? ctx.id : null;

        const parts = await loadCharacterParts(characterId);

        // Generate new ID (max existing + 1)
        const maxId = parts.reduce((max, p) => Math.max(max, parseInt(p.id) || 0), 0);
        const newPart = {
            ...payload,
            id: String(maxId + 1),
            enabled: true,
            created: new Date().toISOString(),
            updated: new Date().toISOString()
        };

        parts.push(newPart);
        await saveCharacterParts(characterId, parts);

        res.json({
            success: true,
            part: newPart,
            message: `Part "${newPart.name}" created successfully`
        });
    } catch (error) {
        console.error('Error creating part:', error);
        res.status(500).json({
            success: false,
            error: 'Failed to create part',
            message: error.message
        });
    }
});

// Get a single part — character-aware sibling of the list route above.
//
// The microphone Gain slider and the STT auto-tune panel persist through a
// GET-then-PUT of this exact URL. The route never existed: the 404 came back
// as HTML, r.json() threw, and the trailing empty .catch() swallowed it — so
// the sliders "saved" nothing, silently, on every use (v11 audit F7).
router.get('/api/parts/:id', async (req, res) => {
    try {
        const ctx = await resolveCharacter(req);
        const characterId = ctx ? ctx.id : null;
        const parts = await loadCharacterParts(characterId);
        const part = parts.find(p => String(p.id) === String(req.params.id));
        if (!part) {
            return res.status(404).json({ success: false, error: 'Part not found' });
        }
        res.json({ success: true, part });
    } catch (error) {
        console.error('Error loading part:', error);
        res.status(500).json({ success: false, error: 'Failed to load part' });
    }
});

// Update existing part - character-aware version
router.put('/api/parts/:id', express.json(), async (req, res) => {
    try {
        const { id } = req.params;
        const updates = req.body;

        // Same identity-key validation as the overrides route below: this PUT
        // merges updates.config into parts.json verbatim, so a bad servoType,
        // rotationRangeDeg, or channel would otherwise land unchecked.
        const validation = validatePartConfigPatch(updates && updates.config);
        if (!validation.ok) {
            return res.status(400).json({ success: false, error: validation.error });
        }

        const ctx = await resolveCharacter(req);
        const characterId = ctx ? ctx.id : null;

        const parts = await loadCharacterParts(characterId);
        const partIndex = parts.findIndex(p => String(p.id) === String(id));

        if (partIndex === -1) {
            return res.status(404).json({
                success: false,
                error: 'Part not found'
            });
        }

        // Update part with new data.
        //
        // `config` is MERGED, not replaced. A shallow spread of `updates` used to
        // overwrite the whole config object, and the Edit-Part form sends only a
        // per-type whitelist (7 keys for a servo, 5 for a webcam). So every config
        // key written by a DIFFERENT surface was destroyed by an unrelated save:
        // the Advanced tab's motionTracking/headTracking tuning and pan-servo
        // assignment, and the Model/Overrides tab's values, all vanished the next
        // time someone corrected an fps field and pressed Save. The operator got a
        // "saved successfully" toast for silently discarding their own calibration
        // work — on the page they use to do that work.
        //
        // Merging means a PUT can no longer REMOVE a config key implicitly, which is
        // correct: this form has no delete affordance (blank fields are skipped), so
        // an absent key has always meant "not edited", never "delete this". A caller
        // that genuinely wants to clear a value sends it explicitly as null.
        const mergedConfig = (updates && updates.config && typeof updates.config === 'object'
            && !Array.isArray(updates.config))
            ? deepMerge(parts[partIndex].config || {}, updates.config)
            : (updates ? updates.config : undefined);

        parts[partIndex] = {
            ...parts[partIndex],
            ...updates,
            ...(mergedConfig !== undefined ? { config: mergedConfig } : {}),
            id, // Ensure ID doesn't change
            updated: new Date().toISOString()
        };

        await saveCharacterParts(characterId, parts);

        res.json({
            success: true,
            part: parts[partIndex],
            message: `Part ${parts[partIndex].name} updated successfully`
        });
    } catch (error) {
        console.error('Error updating part:', error);
        res.status(500).json({
            success: false,
            error: 'Failed to update part',
            message: error.message
        });
    }
});

