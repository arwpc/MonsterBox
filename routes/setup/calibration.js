// Generic: list all positions by Part (continuous or other servo types)
router.get('/api/servos/:id/positions', async (req, res) => {
    try {
        const partId = req.params.id;
        const ctx = await resolveCharacter(req);
        // Reads the real store. This used to go through a stub that returned an empty
        // array, so the endpoint answered "no positions" for every part on the fleet
        // regardless of what had been saved.
        const profile = await readProfileRaw(partId, ctx ? ctx.id : null);
        if (!profile) return res.json({ success: true, type: null, positions: {} });

        const outPositions = {};
        presetsOf(profile).forEach((preset) => {
            if (!preset || !preset.name) return;
            const entry = {};
            if (preset.angle != null) entry.angle = preset.angle;
            if (preset.p != null) entry.p = preset.p;
            if (preset.speed != null) entry.speed = preset.speed;
            if (preset.duration != null) entry.duration = preset.duration;
            outPositions[preset.name] = entry;
        });
        const pulses = profile.pulses || {};
        if (pulses.minUs != null && !outPositions.min) outPositions.min = { pulse_us: pulses.minUs };
        if (pulses.maxUs != null && !outPositions.max) outPositions.max = { pulse_us: pulses.maxUs };
        if (pulses.centerUs != null && !outPositions.neutral) outPositions.neutral = { pulse_us: pulses.centerUs };
        if (pulses.stopUs != null && !outPositions.stop) outPositions.stop = { pulse_us: pulses.stopUs };

        res.json({
            success: true,
            type: (profile.capability && profile.capability.kind) || 'unknown',
            positions: outPositions
        });
    } catch (error) {
        console.error('Error getting positions by part:', error);
        res.status(500).json({ success: false, error: 'Failed to get positions', message: error.message });
    }
});

